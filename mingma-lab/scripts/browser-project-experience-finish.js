return (async () => {
  if (location.hostname !== '127.0.0.1' || location.port !== '5214') throw Error('Run only on isolated QA port 5214');
  const checks = [];
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  const until = async (fn, label) => { for (let n = 0; n < 150; n++) { if (fn()) return; await wait(100) } throw Error(label) };
  const check = (condition, label) => { if (!condition) throw Error(label); checks.push(label) };
  const click = selector => { const el = document.querySelector(selector); if (!el || el.disabled) throw Error(`Unavailable: ${selector}`); el.click() };
  await until(() => document.querySelector('#intake-brief'), 'Restored intake ready');
  check(document.querySelector('#intake-brief').value === '卫生间想做干湿分离，保留浴室柜，地面要防滑。刷新恢复验收。', 'Full expression survives a reload');
  check(document.querySelector('[data-project-scope]').textContent.includes('卫生间'), 'Room context survives reload');
  location.hash = 'overview';
  await until(() => document.querySelector('[data-action="resume-project"]'), 'Home provides resume action');
  check(document.querySelector('[data-action="resume-project"]').textContent.includes('需求共创'), 'Resume names the last workspace step');
  click('[data-action="demo"]');
  await until(() => document.querySelector('[data-action="confirm-demo"]'), 'Existing draft requires replacement confirmation');
  click('[data-action="confirm-demo"]');
  await until(() => document.querySelector('[data-action="seed"]'), 'Demo comparison ready');
  click('[data-action="seed"]');
  await until(() => document.querySelector('.comparison-insights'), 'Differences visible');
  check(document.querySelector('.comparison-insights li').dataset.kind === 'must-conflict', 'Must-item conflict is ranked above missing details');
  check(document.querySelector('.comparison-insights').textContent.includes('供水'), 'Missing services have a readable explanation');
  check(!document.querySelector('.proposal-reference').open, 'Style samples no longer push comparison below the fold');
  click('.comparison-insights [data-action="comparison-focus"]');
  check(document.activeElement?.dataset.comparisonRow === 'K05', 'Summary focuses the matching evidence row');
  click('[data-action="go-space"]');
  await until(() => document.querySelector('.project-space'), 'Current project space shown');
  check(document.querySelector('[data-action="space-project"]').getAttribute('aria-pressed') === 'true', 'Space defaults to current project');
  click('[data-project-room="kitchen"]');
  check(document.querySelectorAll('.project-space-needs li').length === 6, 'Kitchen shows its six associated needs');
  check(document.querySelector('[data-floor-room="kitchen"]').classList.contains('is-selected'), 'Current room highlighted in model');
  click('[data-project-room="bedroom"]');
  check(document.querySelector('.project-space-needs').textContent.includes('还没有'), 'Unmatched room has an honest empty state');
  click('[data-action="export"]'); click('[data-action="report-preview"]');
  await until(() => document.querySelector('.project-report-frame')?.contentDocument?.querySelector('[data-report-print]'), 'Readable report loaded');
  const frame = document.querySelector('.project-report-frame');
  const report = frame.contentDocument;
  check(report.body.textContent.includes('逐项回应与原文证据') && report.body.textContent.includes('待补充与待确认'), 'Report includes evidence and unresolved work');
  check(report.querySelector('svg[aria-label="当前户型房间位置示意"]'), 'Report includes current structured floorplan');
  let printed = false; frame.contentWindow.print = () => { printed = true };
  report.querySelector('[data-report-print]').click();
  check(printed, 'PDF control invokes the report print surface');
  report.querySelector('[data-report-close]').click();
  check(!document.querySelector('.project-report-frame') && document.body.style.overflow !== 'hidden', 'Closing report restores app interaction');
  await wait(400);
  await until(() => document.querySelector('[data-project-save]')?.textContent.includes('已保存'), 'Final project saved');
  return { checks, location: location.href };
})()
