return (async () => {
  const checks = [];
  const check = (ok, label) => { if (!ok) throw new Error(label); checks.push(label); };
  const tick = () => new Promise(r => setTimeout(r, 80));
  const click = async selector => { const el = document.querySelector(selector); if (!el) throw new Error(`Missing ${selector}`); el.click(); await tick(); };
  const change = async (selector, value) => { const el = document.querySelector(selector); if (!el) throw new Error(`Missing ${selector}`); el.value = value; el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })); await tick(); };
  check(!document.querySelector('.home-workbench a[href="#assessment"]'), 'assessment is not accessible before requirements');
  await click('[data-action="demo"]');
  await click('.studio-navigation a[href="#assessment"]');
  check(document.querySelectorAll('.assessment-dimension').length === 8, 'all eight dimensions are visible');
  check(document.querySelector('[data-assessment-filter="budget"]').textContent.includes('待评估'), 'budget without evidence remains unevaluated');
  const initialCount = document.querySelectorAll('.assessment-issue').length;
  await click('.assessment-resolution summary');
  await change('.assessment-resolution select', '现场人员');
  await change('.assessment-resolution textarea', '已安排周末到场核实，记录尺寸后由商家更新方案。');
  document.querySelector('.assessment-resolution form').requestSubmit(); await tick();
  check(document.querySelector('.assessment-note').textContent.includes('现场人员'), 'responsible person and evidence note are saved');
  check(document.querySelectorAll('.assessment-issue').length === initialCount, 'saving a note does not silently resolve risks');
  await click('[data-assessment-filter="budget"]');
  check(document.querySelector('.assessment-empty').textContent.includes('还需要更多依据'), 'dimension filtering explains missing evidence');
  await click('[data-assessment-filter="all"]');
  await click('.assessment-issue [data-action="assessment-edit"]');
  await change('#req-description', document.querySelector('#req-description').value + ' 补充：安装前现场复核。');
  document.querySelector('#requirement-form').requestSubmit(); await tick();
  check(document.querySelector('.assessment-summary.is-stale'), 'editing source marks the old assessment stale');
  await click('[data-action="assessment-run"]');
  check(!document.querySelector('.assessment-summary.is-stale'), 'explicit reassessment replaces stale results');
  check(!document.querySelector('.assessment-note'), 'old task evidence is not inherited by a changed requirement');
  await change('#assessment-target', 'requirements:1');
  await click('.assessment-issue [data-action="assessment-source"]');
  check(!document.querySelector('.dialog-body').textContent.includes('补充：安装前现场复核'), 'published requirement keeps its original source');
  await click('[data-action="close-dialog"]');
  await change('#assessment-target', 'draft');
  await click('.studio-navigation a[href="#requirements"]');
  await click('[data-action="publish"]');
  await click('[data-action="confirm-publish"]');
  check(location.hash === '#compare', 'site checks do not block publishing consultation requirements');
  await click('[data-action="seed"]');
  await click('[data-action="go-vendor"]');
  await click('[data-vendor="b"]');
  await change('[data-commit="K01"]', 'no');
  await change('[data-proposal-text="K01"]', '无法满足此项必须需求。');
  await click('[data-action="submit-vendor"]');
  await click('.comparison tfoot td:last-child [data-action="select-proposal"]');
  await click('[data-action="confirm-selection"]');
  check(location.hash === '#assessment' && document.querySelector('.assessment-summary.is-blocked'), 'must-item conflict blocks actual selection handler');
  check(!document.querySelector('[data-action="assessment-select"]'), 'blocked results do not offer a select action');
  const before = document.querySelectorAll('.risk-high').length;
  await click('[id="risk-response:K01"] .assessment-resolution summary');
  await change('[id="risk-response:K01"] textarea', '已知晓，但原方案尚未修改。');
  document.querySelector('[id="risk-response:K01"] form').requestSubmit(); await tick();
  check(document.querySelectorAll('.risk-high').length === before, 'acknowledgement cannot waive a mandatory conflict');
  await click('[id="risk-response:K01"] [data-action="assessment-edit"]');
  for (const select of document.querySelectorAll('[data-commit]')) { select.value = 'partial'; select.dispatchEvent(new Event('change', { bubbles: true })); }
  for (const text of document.querySelectorAll('[data-proposal-text]')) { text.value = '按需求范围补充方案，现场条件待核实。'; text.dispatchEvent(new Event('input', { bubbles: true })); }
  await click('[data-action="submit-vendor"]');
  await click('.comparison tfoot td:last-child [data-action="assessment-open"]');
  check(!document.querySelector('.assessment-summary.is-blocked'), 'a revised proposal clears explicit denial while keeping pending checks');
  await click('[data-action="assessment-select"]');
  await click('[data-action="confirm-selection"]');
  check(location.hash === '#records', 'revised proposal can be selected with pending work');
  await click('[data-action="selection-detail"]');
  check(document.querySelector('.assessment-archive')?.textContent.includes('当时的风险评估'), 'selection record contains its immutable assessment snapshot');
  await click('[data-action="close-dialog"]');
  await click('[data-action="version"][data-version="2"]');
  check(document.querySelector('.assessment-archive'), 'published requirement also retains assessment snapshot');
  await click('[data-action="close-dialog"]');
  let exported;
  const original = URL.createObjectURL;
  URL.createObjectURL = blob => { exported = blob; return original(blob); };
  await click('[data-action="export"]');
  URL.createObjectURL = original;
  const project = JSON.parse(await exported.text());
  check(project.assessments.length > 3 && project.selection.assessment && project.snapshots.find(s=>s.version===2).assessment, 'project export includes assessment history and snapshots');
  await click('.studio-navigation a[href="#assessment"]');
  check(document.documentElement.scrollWidth <= innerWidth, 'assessment fits current viewport');
  return { checks, viewport: innerWidth, url: location.href };
})()
