// Run after opening “墙体拆除” from the generated demo floorplan.
return (async () => {
  const passed=[], wait=ms=>new Promise(resolve=>setTimeout(resolve,ms))
  const check=(value,label)=>{if(!value)throw new Error(label);passed.push(label)}
  const click=selector=>document.querySelector(selector).click()
  const expanded=()=>[...document.querySelectorAll('[data-wall-piece][data-expanded="true"]')]
  const count=document.querySelectorAll('[data-wall-piece]').length
  check(count>0,'wall pieces come from the floorplan')
  click('[data-wall-mode="all"]');await wait(800)
  check(expanded().length===count,'whole expansion moves all pieces')
  const room=document.querySelector('[data-wall-room]')
  room.value='bedroom';room.dispatchEvent(new Event('change',{bubbles:true}));await wait(800)
  check(document.querySelector('.wall-explorer').dataset.mode==='room','room selection enters room expansion')
  check(expanded().length===document.querySelectorAll('[data-wall-select]').length,'only walls adjoining the chosen room expand')
  check(expanded().length<count,'other rooms remain assembled')
  click('[data-wall-mode="wall"]');await wait(800)
  check(expanded().length===1,'single-wall mode moves one wall')
  const next=[...document.querySelectorAll('[data-wall-piece]')].find(w=>w.getAttribute('aria-pressed')==='false')
  next.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}));await wait(800)
  check(next.getAttribute('aria-pressed')==='true'&&expanded()[0]===next,'keyboard wall selection changes the expanded piece')
  const slider=document.querySelector('#wall-spread');slider.value='45';slider.dispatchEvent(new Event('input',{bubbles:true}));await wait(700)
  check(document.querySelector('output[for="wall-spread"]').textContent==='45%','spread control preserves a partial expansion')
  click('[data-wall-action="mark"]')
  check(document.querySelectorAll('.wall-piece.is-marked').length===1,'mark applies only to the selected wall')
  click('[data-wall-action="preview"]');await wait(800)
  check(Number(getComputedStyle(document.querySelector('.wall-piece.is-marked')).opacity)<.1,'after preview removes the marked wall from the visible shell')
  click('[data-wall-action="restore"]');await wait(800)
  check(expanded().length===0&&document.querySelector('.wall-explorer').dataset.preview==='false','restore assembles walls and exits after preview')
  check(Number(getComputedStyle(document.querySelector('.wall-piece.is-marked')).opacity)>.9,'restore shows marked wall again')
  click('[data-wall-action="back"]')
  check(document.querySelector('.room-planning').dataset.stage==='model','back returns to the original furnished model')
  check(document.querySelectorAll('[data-model-wall]').length>0,'demolition preview does not delete source model walls')
  click('[data-plan-step="walls"]')
  check(document.querySelectorAll('.wall-piece.is-marked').length===1,'reopening retains current-session marks')
  click('[data-wall-action="clear"]')
  check(!document.querySelector('.wall-piece.is-marked')&&document.querySelector('[data-wall-action="preview"]').disabled,'clear removes marks and disables empty preview')
  check(document.documentElement.scrollWidth<=innerWidth,'no horizontal page overflow')
  return passed
})()
